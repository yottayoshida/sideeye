def selftest():
    failed = 0
    for name, leg in LEGS:
        with tempfile.TemporaryDirectory() as tmp:
            try:
                ok, detail = leg(tmp)
            except Broken as exc:
                ok, detail = False, ["BROKEN " + str(exc)]
            if ok:
                print("== ok: %s" % name)
            else:
                failed += 1
                print("== self-test FAILED: %s" % name)
                print("\n".join("     | %s" % d for d in detail))
    return 2 if failed else 0


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", choices=["fetch", "deliver"])
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    root = F.repo_root()
    try:
        if args.selftest:
            return selftest()
        if args.mode == "fetch":
            lines = fetch(root, gh_graphql, gh_search, repo_owner(root))
        elif args.mode == "deliver":
            lines = deliver(root, os.environ.get("GITHUB_RUN_ID", "local"))
        else:
            ap.error("a mode, or --selftest")
    except Broken as exc:
        print("BROKEN %s" % exc)
        return 2
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
