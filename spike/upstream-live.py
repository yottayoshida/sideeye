#!/usr/bin/env python3
"""upstream-live.py — what the trackers say about every report this project filed.

Usage:
  python3 spike/upstream-live.py fetch       # read every report and its pull requests,
                                             # write spike/upstream-live.tsv
  python3 spike/upstream-live.py deliver     # (the upstream-watch job) open, replace or
                                             # close the one bot pull request
  python3 spike/upstream-live.py --selftest

`fetch` reads every report in spike/upstream-reports.tsv, and every issue the repository's
owner opened on someone else's repository that names Sideeye in its body and is not in
that ledger yet -- a report filed and not yet recorded. For each: its state, its title, the
description of the repository it was filed on, the pull requests in that repository that
are linked to it or mention it, and the day it was opened. It writes nothing unless every
report was read and the search answered. A
report the tracker no longer has is written as `gone`; when most of the reports that were
readable last time come back gone, the token is suspect rather than the trackers, and
that is a failure too.

`deliver` compares the two generated files (spike/upstream-live.tsv, docs/found.md) with
main and with the open bot pull request, and leaves at most one bot pull request open.
It never edits spike/outcome-funnel.tsv: a tracker closing a report says nothing about
whether the fix holds (ADR 0125).

Exit 0 done, 2 could not read or could not deliver.
"""

import argparse
import datetime
import importlib.util
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def _load_funnel():
    spec = importlib.util.spec_from_file_location(
        "outcome_funnel", os.path.join(HERE, "outcome-funnel.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


F = _load_funnel()
Broken = F.Broken

CHUNK = 15
PREFIX = "bot/upstream-watch-"
BOT_LOGIN = "app/github-actions"
FILES = (F.LIVE, F.FOUND)
REF_RE = re.compile(r"[\w.-]+/[\w.-]+#\d|github\.com/[^\s]*/issues/")

ISSUE_FIELDS = (
    "state stateReason title createdAt body "
    "closedByPullRequestsReferences(first: 50, includeClosedPrs: true) "
    "{ nodes { number state repository { nameWithOwner } } } "
    "timelineItems(first: 100, itemTypes: [CROSS_REFERENCED_EVENT]%s) "
    "{ pageInfo { hasNextPage endCursor } nodes { ... on CrossReferencedEvent "
    "{ source { __typename ... on PullRequest { number state repository "
    "{ nameWithOwner } } } } } }")

HEADER = """\
# What each report's tracker said at the last read. GENERATED by
# `python3 spike/upstream-live.py fetch`, every day by the upstream-watch job: edit
# spike/upstream-reports.tsv, never this. docs/found.md renders it.
#
# Columns (tab-separated, exactly seven):
#
#   owner/repo  number  state  about  title  pull_requests  opened
#
#   state          open, closed-completed, closed-not_planned, closed-duplicate, or gone
#                  (the tracker answers that the issue or its repository does not exist)
#   about, title   the repository's description and the issue's title, as plain text
#   pull_requests  N:open|closed|merged, comma-separated by number, or -. Pull requests
#                  in the report's own repository, linked to the issue or mentioning it
#   opened         the day the issue was opened, or - for one that is gone
#
# A row whose report is not in spike/upstream-reports.tsv is a filing the search found
# and nobody has recorded yet; docs/found.md lists it as such.
# No reading date: a date would change every day and open a pull request every day.
"""


def repo_query(alias, owner, name, number, after=None):
    after_s = ", after: %s" % json.dumps(after) if after else ""
    return "%s: repository(owner: %s, name: %s) { description issue(number: %d) { %s } }" % (
        alias, json.dumps(owner), json.dumps(name), int(number), ISSUE_FIELDS % after_s)


def gh_graphql(query):
    proc = subprocess.run(["gh", "api", "graphql", "-f", "query=query { %s }" % query],
                          capture_output=True, text=True, stdin=subprocess.DEVNULL)
    try:
        doc = json.loads(proc.stdout)
    except ValueError:
        raise Broken("gh api graphql exited %d with no JSON: %s"
                     % (proc.returncode, (proc.stderr or proc.stdout).strip()[:300]))
    if not isinstance(doc, dict) or ("data" not in doc and "errors" not in doc):
        raise Broken("gh api graphql answered without data: %s" % str(doc)[:300])
    return doc


def pull_numbers(repo, issue, extra_pages):
    """Same-repository pull requests only: a mention from this project's own pull
    requests or from a stranger's fork is not work on the fix."""
    found = {}
    nodes = [n for n in issue["closedByPullRequestsReferences"]["nodes"] if n]
    for page in [issue["timelineItems"]] + extra_pages:
        nodes += [n["source"] for n in page["nodes"]
                  if n and n.get("source", {}).get("__typename") == "PullRequest"]
    for n in nodes:
        if n["repository"]["nameWithOwner"].lower() == repo.lower():
            found[int(n["number"])] = n["state"].lower()
    return ",".join("%d:%s" % (k, found[k]) for k in sorted(found)) or "-"


def read_all(reports, gh):
    out, naming = {}, set()
    for start in range(0, len(reports), CHUNK):
        chunk = reports[start:start + CHUNK]
        aliases = {"r%d" % i: u for i, u in enumerate(chunk)}
        doc = gh(" ".join(repo_query(a, *u["owner"].split("/"), u["number"])
                          for a, u in aliases.items()))
        gone = set()
        data = doc.get("data") or {}
        for err in doc.get("errors") or []:
            path = err.get("path") or []
            alias = path[0] if path else None
            node = data.get(alias) if alias in aliases else None
            # Only the repository or the issue itself: a NOT_FOUND deeper in an issue that
            # answered would call a live report gone.
            if (err.get("type") == "NOT_FOUND" and alias in aliases
                    and path[1:] in ([], ["issue"]) and not (node or {}).get("issue")):
                gone.add(alias)
            else:
                raise Broken("the tracker refused a read: %s" % str(err)[:300])
        for alias, u in aliases.items():
            node = data.get(alias)
            if alias in gone:
                out[u["report"]] = ("gone", "-", "-", "-", "-")
                continue
            if not node or not node.get("issue"):
                raise Broken("%s came back empty with no reason given" % u["report"])
            issue = node["issue"]
            if re.search(r"sideeye", issue.get("body") or "", re.I):
                naming.add(u["report"])
            extra, page = [], issue["timelineItems"]
            while page["pageInfo"]["hasNextPage"]:
                more = gh(repo_query("p0", *u["owner"].split("/"), u["number"],
                                     after=page["pageInfo"]["endCursor"]))
                if more.get("errors") or not (more.get("data") or {}).get("p0"):
                    raise Broken("%s: the next page of its timeline could not be read"
                                 % u["report"])
                page = more["data"]["p0"]["issue"]["timelineItems"]
                extra.append(page)
            if issue["state"] == "OPEN":
                state = "open"
            elif issue.get("stateReason"):
                state = "closed-" + issue["stateReason"].lower()
            else:
                state = "closed"
            out[u["report"]] = (state, F.plain(node.get("description")),
                                F.plain(issue.get("title")),
                                pull_numbers(u["owner"], issue, extra),
                                (issue.get("createdAt") or "-")[:10])
    return out, naming


def gh_search(owner):
    proc = subprocess.run(
        ["gh", "api", "-X", "GET", "search/issues", "--paginate",
         "-f", "q=author:%s is:issue -user:%s" % (owner, owner), "-f", "per_page=100",
         "-q", '(if .incomplete_results then "INCOMPLETE" else empty end),'
               ' (.items[] | [(.repository_url | sub("^.*/repos/"; "")), (.number | tostring),'
               ' ((.body // "") | test("sideeye"; "i") | tostring)] | @tsv)'],
        capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if proc.returncode != 0:
        raise Broken("the issue search failed (exit %d): %s"
                     % (proc.returncode, (proc.stderr or proc.stdout).strip()[:300]))
    return parse_search(proc.stdout)


def parse_search(text):
    lines = [line for line in text.splitlines() if line]
    # Not taken as an answer: a search that timed out returns what it had, and a filing
    # missing from it would read as one nobody made.
    if "INCOMPLETE" in lines:
        raise Broken("the issue search answered with incomplete results")
    return [(r, n, m == "true") for r, n, m in (line.split("\t") for line in lines)]


def repo_owner(root):
    owner = os.environ.get("GITHUB_REPOSITORY_OWNER")
    if owner:
        return owner
    url = run(["git", "-C", root, "remote", "get-url", "origin"]).strip()
    m = re.search(r"github\.com[:/]([^/]+)/", url)
    if not m:
        raise Broken("cannot tell the repository's owner from origin %r" % url)
    return m.group(1)


def unrecorded(found, ledger, listed):
    """Not every issue the owner opens elsewhere: a listing of another project on someone's
    directory is one too, and would appear on this project's page as a finding. One the
    page already lists is read again whatever the search says, so a search that misses it
    cannot take it off the page, and a deleted one shows as gone."""
    known = {u["report"] for u in ledger}
    keys = {(r, n) for r, n, names in found if names} | set(listed)
    out = []
    for repo, number in sorted(keys, key=lambda k: (k[0].lower(), int(k[1]))):
        report = "%s#%s" % (repo, number)
        if report not in known:
            out.append({"owner": repo, "number": number, "report": report})
    return out


def render(reports, states):
    lines = [HEADER]
    for u in reports:
        lines.append("\t".join([u["owner"], u["number"]] + list(states[u["report"]])) + "\n")
    return "".join(lines)


def fetch(root, gh, search, owner):
    ledger = F.read_upstream(root)
    if not ledger:
        raise Broken("spike/upstream-reports.tsv names no report")
    path = os.path.join(root, F.LIVE)
    previous = F.read_live(root) if os.path.exists(path) else {}
    listed = [(l["owner"], l["number"]) for l in previous.values()]
    reports = ledger + unrecorded(search(owner), ledger, listed)
    states, naming = read_all(reports, gh)
    # A row the page listed once is dropped when its body stops naming Sideeye; one that is
    # gone stays, because the filing happened.
    known = {u["report"] for u in ledger}
    reports = [u for u in reports if u["report"] in known or u["report"] in naming
               or states[u["report"]][0] == "gone"]
    readable = [r for r, l in previous.items() if l["state"] != "gone"]
    now_gone = [r for r in readable if states.get(r, ("",))[0] == "gone"]
    if readable and len(now_gone) * 2 > len(readable):
        raise Broken("%d of the %d reports readable last time are gone now -- a token or "
                     "permission problem, not %d deleted issues"
                     % (len(now_gone), len(readable), len(now_gone)))
    text = render(reports, states)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, path)
    return ["read %d reports, %d of them not recorded yet: %d gone"
            % (len(reports), len(reports) - len(ledger),
               sum(1 for s in states.values() if s[0] == "gone"))]


def decide(new, main, pr):
    """Not compared on the whole tree: it differs every time main moves, and would replace
    the pull request daily."""
    if new == main:
        return "close"
    if pr is not None and new == pr:
        return "keep"
    return "replace"


def changed_reports(old_live, new_live, ledger):
    """Tool names and field names only. Never the report's owner/repo#N or upstream's
    words: a pull request body or commit message naming an issue puts this project's bot
    on that issue's timeline every day it changes."""
    fields = ("state", "pull requests", "description", "title")
    keys = ("state", "prs", "about", "title")
    recorded = {u["report"]: u["finding"] for u in ledger}
    out = []
    for report in list(recorded) + sorted((set(old_live) | set(new_live)) - set(recorded)):
        old, new = old_live.get(report), new_live.get(report)
        if new is None:
            if old is not None:
                out.append((recorded.get(report) or old["owner"].split("/")[1],
                            ["no longer listed"]))
            continue
        if old is not None and all(old[k] == new[k] for k in keys):
            continue
        tool = recorded.get(report) or "a new filing on %s" % new["owner"].split("/")[1]
        what = ["first read"] if old is None else [
            f for f, k in zip(fields, keys) if old[k] != new[k]]
        if report not in recorded:
            what.append("not in spike/upstream-reports.tsv yet")
        out.append((tool, what))
    return out


def pr_text(changes):
    n = len(changes)
    if n:
        title = "upstream-watch: %d report%s changed on %s tracker%s" % (
            n, "" if n == 1 else "s", "its" if n == 1 else "their", "" if n == 1 else "s")
        body = ["The daily read of every report in `spike/upstream-reports.tsv` found %d "
                "changed since main:" % n, ""]
        body += ["- %s: %s" % (tool, ", ".join(what)) for tool, what in changes]
    else:
        title = "upstream-watch: the found page regenerated after the record changed"
        body = ["No report changed on its tracker since main. The record did — a filing was "
                "recorded or a stage moved — and the regenerated rows differ from main's."]
    if any("not in spike/upstream-reports.tsv yet" in what for _t, what in changes):
        body += ["", "A filing that is not recorded yet is listed on the page already. Record "
                 "it as `spike/upstream-report-template.md` (After filing) says: its row in "
                 "`spike/upstream-reports.tsv`, its marker in `docs/target-classes.md`, its "
                 "funnel row, and its campaign's row in `spike/campaign-versions.tsv`."]
    body += ["", "Regenerated `spike/upstream-live.tsv` and `docs/found.md`, nothing else; "
             "the rows are in `docs/found.md`'s diff. A report that closed may need its row "
             "in `spike/outcome-funnel.tsv` moved after re-measuring, which this job never "
             "does.", "",
             "CI on this pull request waits for approval (it was opened with the job's own "
             "token): **Approve workflows to run**, then merge when green."]
    text = "\n".join(body)
    for part in (title, text):
        if REF_RE.search(part):
            raise Broken("refusing a pull request whose text names an upstream issue: %r"
                         % REF_RE.search(part).group(0))
    return title, text


def run(cmd, **kw):
    proc = subprocess.run(cmd, capture_output=True, text=True, stdin=subprocess.DEVNULL, **kw)
    if proc.returncode != 0:
        raise Broken("%s exited %d: %s" % (" ".join(cmd[:3]), proc.returncode,
                                            (proc.stderr or proc.stdout).strip()[:300]))
    return proc.stdout


def _read_bytes(path):
    with open(path, "rb") as fh:
        return fh.read()


def git_show(root, ref, path):
    proc = subprocess.run(["git", "-C", root, "show", "%s:%s" % (ref, path)],
                          capture_output=True, stdin=subprocess.DEVNULL)
    return proc.stdout if proc.returncode == 0 else None


def read_live_text(text):
    with tempfile.TemporaryDirectory() as tmp:
        os.makedirs(os.path.join(tmp, "spike"))
        with open(os.path.join(tmp, F.LIVE), "w", encoding="utf-8") as fh:
            fh.write(text)
        return F.read_live(tmp)


def deliver(root, run_id):
    changed = [line[3:] for line in run(["git", "-C", root, "status", "--porcelain"])
               .splitlines()]
    stray = [p for p in changed if p not in FILES]
    if stray:
        raise Broken("regenerating changed files it does not own: %s" % ", ".join(stray))
    new = tuple(_read_bytes(os.path.join(root, p)) for p in FILES)
    main = tuple(git_show(root, "HEAD", p) for p in FILES)

    listed = json.loads(run(["gh", "pr", "list", "--state", "open", "--limit", "100",
                             "--json", "number,headRefName,author"], cwd=root))
    bots = sorted((p for p in listed if p["headRefName"].startswith(PREFIX)
                   and p["author"]["login"] == BOT_LOGIN),
                  key=lambda p: p["number"], reverse=True)
    for extra in bots[1:]:
        run(["gh", "pr", "close", str(extra["number"]), "--delete-branch", "--comment",
             "Closed: only the newest upstream-watch pull request stays open."], cwd=root)
    keep = bots[0] if bots else None
    pr = None
    if keep:
        run(["git", "-C", root, "fetch", "--quiet", "origin", keep["headRefName"]])
        pr = tuple(git_show(root, "FETCH_HEAD", p) for p in FILES)

    action = decide(new, main, pr)
    if action == "close":
        if keep:
            run(["gh", "pr", "close", str(keep["number"]), "--delete-branch", "--comment",
                 "Closed: main already says what the trackers say."], cwd=root)
        return ["main matches the trackers%s" % (" -- closed #%d" % keep["number"]
                                                  if keep else "")]
    if action == "keep":
        return ["#%d already says what the trackers say" % keep["number"]]

    old_live = read_live_text(main[0].decode("utf-8")) if main[0] else {}
    title, body = pr_text(changed_reports(old_live, F.read_live(root),
                                          F.read_upstream(root)))
    branch = "%s%s-%s" % (PREFIX, datetime.date.today().isoformat(), run_id)
    ident = ["-c", "user.name=github-actions[bot]",
             "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com"]
    run(["git", "-C", root, "switch", "--quiet", "-c", branch])
    run(["git", "-C", root, "add", "--"] + list(FILES))
    run(["git", "-C", root] + ident + ["commit", "--quiet", "-m", title, "-m", body])
    run(["git", "-C", root, "push", "--quiet", "origin", branch])
    try:
        url = run(["gh", "pr", "create", "--base", "main", "--head", branch,
                   "--title", title, "--body", body], cwd=root).strip()
    except Broken as exc:
        # Not left on the remote: a run that cannot open its pull request would leave one
        # branch behind every day it runs.
        subprocess.run(["git", "-C", root, "push", "--quiet", "origin", "--delete", branch],
                       capture_output=True, stdin=subprocess.DEVNULL)
        raise Broken("%s -- the branch was deleted. If the tracker refused it, the repository "
                     "may not allow GitHub Actions to create pull requests (ADR 0125)" % exc)
    if keep:
        run(["gh", "pr", "close", str(keep["number"]), "--delete-branch", "--comment",
             "Replaced by #%s." % url.rsplit("/", 1)[-1]], cwd=root)
    return ["opened %s%s" % (url, " -- closed #%d" % keep["number"] if keep else "")]


